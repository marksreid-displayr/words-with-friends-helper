import fs from 'node:fs'
import { PNG } from 'pngjs'

const fixtures = JSON.parse(fs.readFileSync(new URL('../src/test/fixtures/expected.json', import.meta.url), 'utf8'))
const candidates = new Map()
const rackCandidates = new Map()

for (const [name, fixture] of Object.entries(fixtures)) {
  const png = PNG.sync.read(fs.readFileSync(new URL(`../src/test/fixtures/${name}-board.png`, import.meta.url)))
  const cell = png.width / 15
  fixture.rows.forEach((rowText, row) => {
    ;[...rowText].forEach((letter, col) => {
      if (letter === '.') return
      const mask = makeMask(png, cell, row, col)
      const component = largestComponent(mask.data, mask.width, mask.height)
      if (!component || component.height < cell * 0.38) return
      const normalized = normalize(component, 32, 32)
      const score = component.height * 1000 + component.area
      const current = candidates.get(letter)
      if (!current || score > current.score) candidates.set(letter, { score, normalized, source: `${name}:${row}:${col}` })
    })
  })

  const rackPng = PNG.sync.read(fs.readFileSync(new URL(`../src/test/fixtures/${name}-rack.png`, import.meta.url)))
  const slot = rackPng.width / 7
  ;[...fixture.rack].forEach((letter, index) => {
    const mask = makeRackMask(rackPng, slot, index)
    const component = largestComponent(mask.data, mask.width, mask.height)
    if (!component) return
    const normalized = normalize(component, 32, 32)
    const score = component.height * 1000 + component.area
    const current = rackCandidates.get(letter)
    if (!current || score > current.score) rackCandidates.set(letter, { score, normalized, source: `${name}:${index}` })
  })
}

const entries = [...candidates.entries()].sort(([a], [b]) => a.localeCompare(b))
const rackEntries = [...rackCandidates.entries()].sort(([a], [b]) => a.localeCompare(b))
const output = `// Generated by scripts/generate-glyph-templates.mjs from anonymized board crops.\n` +
  `// Each value is a normalized 32 × 32 binary mask of the game's tile glyph.\n` +
  `export const GLYPH_TEMPLATES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries.map(([letter, value]) => [letter, value.normalized])), null, 2)})\n` +
  `export const RACK_GLYPH_TEMPLATES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(rackEntries.map(([letter, value]) => [letter, value.normalized])), null, 2)})\n`
fs.writeFileSync(new URL('../src/recognition/glyphTemplates.ts', import.meta.url), output)

process.stdout.write(`Generated ${entries.length} glyphs: ${entries.map(([letter]) => letter).join('')}\n`)
const missing = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ'].filter((letter) => !candidates.has(letter))
if (missing.length) process.stdout.write(`Missing: ${missing.join('')}\n`)
process.stdout.write(`Generated ${rackEntries.length} rack glyphs: ${rackEntries.map(([letter]) => letter).join('')}\n`)

function makeMask(png, cell, row, col) {
  const x0 = Math.round((col + 0.12) * cell)
  const y0 = Math.round((row + 0.16) * cell)
  const width = Math.round(cell * 0.76)
  const height = Math.round(cell * 0.72)
  const data = new Uint8Array(width * height)
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const offset = ((y0 + y) * png.width + x0 + x) * 4
      const red = png.data[offset]
      const green = png.data[offset + 1]
      const blue = png.data[offset + 2]
      const light = red * 0.299 + green * 0.587 + blue * 0.114
      if (light < 150 && red > green * 1.08 && red > blue * 1.12 && red - green > 8) data[y * width + x] = 1
    }
  }
  return { data, width, height }
}

function makeRackMask(png, slot, index) {
  const x0 = Math.round((index + 0.12) * slot)
  const y0 = Math.round(png.height * 0.12)
  const width = Math.round(slot * 0.76)
  const height = Math.round(png.height * 0.74)
  const data = new Uint8Array(width * height)
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const offset = ((y0 + y) * png.width + x0 + x) * 4
      const red = png.data[offset]
      const green = png.data[offset + 1]
      const blue = png.data[offset + 2]
      const light = red * 0.299 + green * 0.587 + blue * 0.114
      if (light < 118) data[y * width + x] = 1
    }
  }
  return { data, width, height }
}

function largestComponent(data, width, height) {
  const seen = new Uint8Array(data.length)
  let best = null
  for (let start = 0; start < data.length; start += 1) {
    if (!data[start] || seen[start]) continue
    const queue = [start]
    seen[start] = 1
    const pixels = []
    let minX = width
    let maxX = 0
    let minY = height
    let maxY = 0
    while (queue.length) {
      const index = queue.pop()
      pixels.push(index)
      const x = index % width
      const y = Math.floor(index / width)
      minX = Math.min(minX, x)
      maxX = Math.max(maxX, x)
      minY = Math.min(minY, y)
      maxY = Math.max(maxY, y)
      for (const [nx, ny] of [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]]) {
        if (nx < 0 || nx >= width || ny < 0 || ny >= height) continue
        const next = ny * width + nx
        if (data[next] && !seen[next]) {
          seen[next] = 1
          queue.push(next)
        }
      }
    }
    const component = { pixels, width: maxX - minX + 1, height: maxY - minY + 1, minX, minY, area: pixels.length, sourceWidth: width }
    if (!best || component.area > best.area) best = component
  }
  return best
}

function normalize(component, width, height) {
  const output = new Uint8Array(width * height)
  const scale = Math.min((width - 4) / component.width, (height - 3) / component.height)
  const targetWidth = Math.max(1, Math.round(component.width * scale))
  const targetHeight = Math.max(1, Math.round(component.height * scale))
  const offsetX = Math.floor((width - targetWidth) / 2)
  const offsetY = Math.floor((height - targetHeight) / 2)
  const sourceSet = new Set(component.pixels)
  for (let y = 0; y < targetHeight; y += 1) {
    for (let x = 0; x < targetWidth; x += 1) {
      const sx = component.minX + Math.min(component.width - 1, Math.floor((x / targetWidth) * component.width))
      const sy = component.minY + Math.min(component.height - 1, Math.floor((y / targetHeight) * component.height))
      if (sourceSet.has(sy * component.sourceWidth + sx)) output[(offsetY + y) * width + offsetX + x] = 1
    }
  }
  return [...output].join('')
}
